"""Phase 5D: teaser check (historical 2022-25, weeks >= 4).

    python -m engine.cfb.model.teasers        # -> TEASERS block of docs/cfb/PHASE5_REPORT.md

DK's CFB teaser prices aren't in the API: data/cfb/manual/teaser_prices.json is filled in by
Tim from the DK app. Break-even per leg = implied(price) ** (1/legs). Until prices are filled,
the analysis sweeps per-leg break-evens of 70/72/74/76% instead of assuming prices.

Each spread leg (both sides of every game): P(cover at the bet-time open line + teaser points)
from the frozen Phase 3 distribution centered on the Phase 3 projection (LOSO 2022-24,
frozen 2025), with pushes from the whole-number mass. Push rule: from the template; default
"leg removed", so the comparable leg probability is P(win) / (P(win) + P(loss)).
A leg "clears" a break-even BE when that probability >= BE + 2 pts.
Spots: dog teased through 3 and 7 = getting +1.5..+2.5 (6-pt teaser -> +7.5..+8.5);
favorite through 7 and 3 = laying -7.5..-8.5 (6-pt -> -1.5..-2.5); otherwise dog/fav/pick.
"""
from __future__ import annotations
import json

import numpy as np
import pandas as pd
from scipy.stats import binomtest

from engine.cfb import config
from engine.cfb.model import distribution as dist, moneyline as ml

TEMPLATE = config.DATA / "manual" / "teaser_prices.json"
SWEEP = (0.70, 0.72, 0.74, 0.76)
POINTS = (6.0, 6.5, 7.0, 10.0)


def break_evens() -> list[dict]:
    t = json.loads(TEMPLATE.read_text()) if TEMPLATE.exists() else {}
    out = []
    for r in t.get("teasers", []):
        if r.get("price") is None:
            continue
        p = float(ml.implied(r["price"]))
        out.append({"label": f"{r['legs']}-team {r['points']} pt @ {r['price']:+d}",
                    "points": float(r["points"]), "be": p ** (1 / r["legs"])})
    return out


def legs() -> pd.DataFrame:
    g, P = ml.projections()
    g = g[(g.week_asof >= 4) & g.eval_set.isin(["2022-2024 LOSO", "2025 holdout"])]
    P = P[g.index]
    rows = []
    m = g.margin_home.to_numpy()
    for side in ("home", "away"):
        line = g.spread_open.to_numpy() if side == "home" else -g.spread_open.to_numpy()
        tm = m if side == "home" else -m
        for T in POINTS:
            L = line + T
            win, push = dist.cover(P, L, side)
            lose = 1 - win - push
            rows.append(pd.DataFrame({
                "game_id": g.game_id.to_numpy(), "season": g.season.to_numpy(), "eval_set": g.eval_set.to_numpy(),
                "side": side, "line": line, "teaser_pts": T, "teased_line": L,
                "p_win": win, "p_push": push, "p_cond": win / np.maximum(win + lose, 1e-9),
                "result": np.where(tm + L > 0, 1.0, np.where(tm + L == 0, np.nan, 0.0))}))
    x = pd.concat(rows, ignore_index=True)
    x["spot"] = np.select(
        [x.line.between(1.5, 2.5), x.line.between(-8.5, -7.5), x.line > 0, x.line < 0],
        ["dog thru 3 & 7", "fav thru 7 & 3", "other dog", "other fav"], default="pick'em")
    return x


def summarize(x: pd.DataFrame, bes: list[dict]) -> pd.DataFrame:
    rows = []
    cases = ([{"label": f"BE {int(b * 100)}% per leg", "points": None, "be": b} for b in SWEEP]
             if not bes else bes)
    for c in cases:
        for T in ([c["points"]] if c["points"] else POINTS):
            y = x[(x.teaser_pts == T) & (x.p_cond >= c["be"] + 0.02)]
            for season, grp in [("all", y)] + list(y.groupby("season")):
                d = grp.dropna(subset=["result"])
                n, k = len(d), int(d.result.sum())
                ci = binomtest(k, n).proportion_ci(method="wilson") if n else None
                rows.append({"case": c["label"], "teaser_pts": T, "season": season, "legs": len(grp),
                             "graded": n, "hit_%": 100 * k / n if n else np.nan,
                             "ci95": f"{100 * ci.low:.1f}-{100 * ci.high:.1f}" if ci else "",
                             "break_even_%": 100 * c["be"], "mean_model_%": 100 * grp.p_cond.mean() if len(grp) else np.nan})
    return pd.DataFrame(rows)


def main() -> int:
    x = legs()
    bes = break_evens()
    s = summarize(x, bes)
    spots = (x[x.teaser_pts == 6].dropna(subset=["result"]).groupby(["spot", "eval_set"])
             .agg(legs=("result", "size"), model_pct=("p_cond", lambda v: 100 * v.mean()),
                  hit_pct=("result", lambda v: 100 * v.mean())).reset_index())
    qual = x[(x.teaser_pts == 6) & (x.p_cond >= 0.74)]
    which = (qual.groupby(["spot"]).agg(legs=("p_cond", "size"), mean_model_pct=("p_cond", lambda v: 100 * v.mean()),
                                        hit_pct=("result", lambda v: 100 * np.nanmean(v))).reset_index())
    T = [f"_Generated by `python -m engine.cfb.model.teasers`. Weeks >= 4, 2022-24 LOSO + 2025 frozen; "
         f"bet-time line = provider open. {'Break-evens from the DK template.' if bes else '**DK teaser prices not filled in yet: break-even sweep (70/72/74/76% per leg), no assumed prices.**'} "
         "Push rule: leg removed (template default)._\n",
         "**Legs clearing break-even by >= 2 pts, realized hit rate vs break-even**\n",
         ml.md(s[s.season == "all"], "{:.1f}"),
         "\n<details><summary>By season</summary>\n\n", ml.md(s[s.season != "all"], "{:.1f}"), "\n</details>\n",
         "\n**6-pt legs by spot: model vs realized (all legs, calibration check)**\n", ml.md(spots, "{:.1f}"),
         "\n**Which spots clear a 74% break-even + 2 (6-pt)?**\n", ml.md(which, "{:.1f}")]
    ml.write_block("TEASERS", "\n".join(T))
    print("\n".join(T))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
