"""When DK opens and how lines move (Phase 4 brief §3).

    python -m engine.cfb.lines.movement            # writes the MOVEMENT/DKOPEN blocks of PHASE4_REPORT.md

Historical (2023-2025, CFBD DK + Bovada open/close, no timestamps): informational.
  * how far each book's open moves to its close; how often DK's open already equals
    Bovada's close
  * the frozen Phase 3 model re-anchored on DK's open (no refit):
        proj_dk = dk_open_margin + k[bucket] * (ratings_margin - dk_open_margin) + b_qb * qb_delta
    CLV vs DK's close, ATS at DK's open, with QB on and off, next to the same games on Bovada.
Forward (2026, from data/cfb/lines/snapshots): first-seen time per game, movement between
snapshot labels, and how |proj - line| shrinks over the week.
"""
from __future__ import annotations
import glob

import numpy as np
import pandas as pd
from scipy.stats import binomtest

from engine.cfb import config
from engine.cfb.lines.capture import SNAP
from engine.cfb.model import features, margin_model as mm, run as mrun

REPORT = config.ROOT / "docs" / "cfb" / "PHASE4_REPORT.md"
EDGES = (1.5, 3.0, 5.0)


def md(df: pd.DataFrame, fmt="{:.2f}") -> str:
    if df is None or df.empty:
        return "_(none)_\n"
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else fmt.format(v))
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "".join("| " + " | ".join(map(str, r)) + " |\n" for r in df.itertuples(index=False))


def write_block(name: str, text: str) -> None:
    doc = REPORT.read_text(encoding="utf-8") if REPORT.exists() else "# CFB Phase 4 Report\n"
    b, e = f"<!-- AUTO:{name}:BEGIN -->", f"<!-- AUTO:{name}:END -->"
    blk = f"{b}\n{text}\n{e}"
    doc = (doc[:doc.index(b)] + blk + doc[doc.index(e) + len(e):]) if b in doc and e in doc \
        else doc + f"\n{blk}\n"
    REPORT.write_text(doc, encoding="utf-8")


# ------------------------------------------------------------------ shared scoring
def clv_ats(open_m, close_m, proj, margin, label: str) -> list[dict]:
    """CLV (close vs open, same book) and ATS at the open, at each edge threshold."""
    x = pd.DataFrame({"o": open_m, "c": close_m, "p": proj, "m": margin}).dropna()
    edge, move = x.p - x.o, x.c - x.o
    rows = []
    for t in EDGES:
        s = edge.abs() >= t
        e, mv = edge[s], move[s]
        moved = mv != 0
        tw = ((np.sign(mv) == np.sign(e)) & moved).sum()
        res = x.m[s] - x.o[s]
        push = res == 0
        win = (np.sign(res) == np.sign(e))[~push]
        n, k = len(win), int(win.sum())
        ci = binomtest(k, n).proportion_ci(method="wilson") if n else None
        rows.append({"set": label, "edge >=": t, "games": int(s.sum()),
                     "clv_toward_%_of_moves": 100 * tw / max(moved.sum(), 1),
                     "avg_move_toward": float((mv * np.sign(e)).mean()) if s.any() else np.nan,
                     "ats_bets": n, "ats_win_%": 100 * k / n if n else np.nan,
                     "ats_ci95": f"{100 * ci.low:.1f}-{100 * ci.high:.1f}" if ci else "",
                     "roi_%_-110": 100 * (k * 100 / 110 - (n - k)) / n if n else np.nan})
    corr = float(np.corrcoef(edge, move)[0, 1]) if len(x) > 2 else np.nan
    for r in rows:
        r["corr"] = corr
    return rows


def model_frame() -> pd.DataFrame:
    d = mm.prep(features.load())
    lines = pd.read_parquet(config.CLEAN / "lines.parquet")
    for book, tag in (("DraftKings", "dk"), ("Bovada", "bov")):
        b = lines[lines.provider == book][["game_id", "spread_open", "spread"]].rename(
            columns={"spread_open": f"{tag}_open_spread", "spread": f"{tag}_close_spread"})
        d = d.merge(b, on="game_id", how="left")
    return d


def project_at(d: pd.DataFrame, open_margin: pd.Series, params: dict, qb: bool = True) -> pd.Series:
    k = d.bucket.map(lambda b: params["coef"][f"k_{b}"])
    out = open_margin + k * (d.ratings_margin - open_margin)
    if qb:
        out = out + params["coef"].get("qb_delta", 0.0) * d.qb_delta.fillna(0)
    return out


# ------------------------------------------------------------------ historical
def historical() -> str:
    params = mrun.load_params()
    d = model_frame()
    d = d[d.margin_home.notna()]
    P = [f"_Generated by `python -m engine.cfb.lines.movement`. Frozen Phase 3 primary, no refit. "
         f"2023-2024 are tuning seasons (in-sample for k); 2025 is the held-out season; 2026 weeks "
         f"4-6 = all completed games to date._\n"]

    # 1. DK vs Bovada open/close
    rows = []
    for s in (2023, 2024, 2025, 2026):
        x = d[d.season == s].dropna(subset=["dk_open_spread", "dk_close_spread"])
        both = x.dropna(subset=["bov_open_spread", "bov_close_spread"])
        rows.append({
            "season": s, "dk_games": len(x),
            "dk_|open-close|": (x.dk_close_spread - x.dk_open_spread).abs().mean(),
            "dk_open==close_%": 100 * (x.dk_close_spread == x.dk_open_spread).mean(),
            "both_books": len(both),
            "bov_|open-close|": (both.bov_close_spread - both.bov_open_spread).abs().mean(),
            "bov_open==close_%": 100 * (both.bov_close_spread == both.bov_open_spread).mean(),
            "dk_open==bov_close_%": 100 * (both.dk_open_spread == both.bov_close_spread).mean(),
            "dk_open==bov_open_%": 100 * (both.dk_open_spread == both.bov_open_spread).mean(),
            "|dk_open-bov_open|": (both.dk_open_spread - both.bov_open_spread).abs().mean(),
        })
    P += ["### DK vs Bovada: open, close, movement (CFBD, FBS vs FBS)\n",
          md(pd.DataFrame(rows), "{:.2f}")]

    # 2. the model vs DK's open, next to Bovada on the same games
    rows = []
    for label, seasons in (("2023", [2023]), ("2024", [2024]), ("2023-2024 (tuning)", [2023, 2024]),
                           ("2025 (holdout)", [2025])):
        x = d[d.season.isin(seasons)].dropna(subset=["dk_open_spread", "dk_close_spread",
                                                      "bov_open_spread", "bov_close_spread"])
        for book in ("dk", "bov"):
            om, cm = -x[f"{book}_open_spread"], -x[f"{book}_close_spread"]
            for qb in (True, False):
                rows += clv_ats(om, cm, project_at(x, om, params, qb), x.margin_home,
                                f"{label} · {'DK' if book == 'dk' else 'Bovada'} open · QB {'on' if qb else 'off'}")
    t = pd.DataFrame(rows)
    P += ["\n### The DK-open test: frozen model anchored on each book's open (same games: both books listed)\n",
          md(t[t["edge >="] == 1.5].drop(columns=["edge >="]), "{:.2f}"),
          "\n<details><summary>All thresholds (1.5 / 3 / 5)</summary>\n\n", md(t, "{:.2f}"),
          "\n</details>\n"]
    return "\n".join(P)


def requested_numbers() -> str:
    """Tim's ask: 2025 QB-off and 2026 wks 4-6 QB on/off, vs the provider open (Phase 3 lines)."""
    params = mrun.load_params()
    d = mm.prep(features.load())
    d = d[d.margin_home.notna()]
    rows = []
    for label, x in (("2025 holdout (Bovada open)", d[d.season == 2025]),
                     ("2026 wks 4-6 (DK open)", d[(d.season == 2026) & d.week_asof.between(4, 6)])):
        for qb in (True, False):
            om = x.open_margin
            rows += clv_ats(om, x.close_margin, project_at(x, om, params, qb), x.margin_home,
                            f"{label} · QB {'on' if qb else 'off'}")
    n26 = len(d[(d.season == 2026) & d.week_asof.between(4, 6)])
    return (f"_2026 weeks 4-6 now include all of week 6 ({n26} completed FBS-vs-FBS games; the Phase 3 "
            f"report had week 6 midweek games only)._\n\n" + md(pd.DataFrame(rows), "{:.2f}"))


# ------------------------------------------------------------------ forward (snapshots)
def forward() -> str:
    files = sorted(glob.glob(str(SNAP / "dk_main_*_wk*.csv")))
    if not files:
        return "_No snapshots yet._\n"
    m = pd.concat(pd.read_csv(f) for f in files)
    m = m[(m.market == "spreads") & (m.is_home == 1)].dropna(subset=["game_id"])
    m["captured_at_utc"] = pd.to_datetime(m.captured_at_utc, utc=True)
    snaps = m.groupby(["captured_at_utc", "label"]).game_id.nunique().reset_index(name="games")
    first = m.sort_values("captured_at_utc").drop_duplicates("game_id")
    first["first_seen_et"] = first.captured_at_utc.dt.tz_convert("America/New_York").dt.strftime("%a %H:%M")
    piv = m.pivot_table(index="game_id", columns="label", values="point", aggfunc="last")
    out = ["**Snapshots so far**\n", md(snaps.assign(captured_at_utc=snaps.captured_at_utc.astype(str))),
           "\n**First seen (by our capture; the open-watch slots start Sun 6 PM ET)**\n",
           md(first.first_seen_et.value_counts().rename_axis("first_seen_et").reset_index(name="games"))]
    if piv.shape[1] > 1:
        moves = {c: (piv[c] - piv.iloc[:, 0]).abs().mean() for c in piv.columns[1:]}
        out += ["\n**Mean |line change| vs first snapshot, by label**\n",
                md(pd.DataFrame({"label": list(moves), "mean_abs_move": list(moves.values())}))]
    else:
        out.append("\nOnly one snapshot label so far: movement needs the scheduled slots.\n")
    return "\n".join(out)


def main() -> int:
    write_block("REQUESTED", requested_numbers())
    write_block("DKOPEN", historical())
    write_block("MOVEMENT", forward())
    print(f"-> {REPORT.relative_to(config.ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
